  assert.equal(shared.trackPointer(node,{pointerId:2,button:0},handlers),false);
  node.dispatchEvent(event('pointermove',2));node.dispatchEvent(event('pointerup',2));
  assert.equal(moves,0);assert.equal(commits,0);
